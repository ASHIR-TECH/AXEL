    """High-level grouping used for dashboards and alert routing."""

    LIVE_GATE = "live_gate"
    APPROVAL = "approval"
    PRE_TRADE = "pre_trade"
    ORDER = "order"
    RECONCILIATION = "reconciliation"
    HALT = "halt"
    INCIDENT = "incident"


