"""
Stable machine-readable reason codes for Phase 6 live operations.

The Phase 6 specification requires that operational logic is never encoded only
in free-text messages (see `docs/AXEL_PHASE_6_RESEARCH_AND_IMPLEMENTATION.md`
§13.1). Every rejection, halt, mismatch and incident therefore carries a stable
enum member that tests and operators can key on.

This module has **zero LLM imports** and is safe to import from `axel.execution`
and `axel.risk`.
"""

from __future__ import annotations

from enum import Enum


